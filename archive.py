import re

from game_round import Round


class ArchiveRound(Round):
    def __init__(self, title, task, hint, clue, examples):
        super().__init__(title, task, hint, clue)
        self.examples = examples

    def check(self, pattern):
        try:
            regex = re.compile(pattern)
        except re.error as error:
            return False, "Шаблон не удалось скомпилировать: " + str(error)

        for message, expected in self.examples:
            found = []
            for match in regex.finditer(message):
                found.append(match.group(0))

            if found != expected:
                return False, ("Ошибка в сообщении:\n  " + message +
                               "\nОжидалось: " + str(expected) +
                               "\nНайдено:   " + str(found))

        return True, "Верно! Все нужные записи найдены."


